create or replace function public.track_vehicle_event(p_vehicle_id bigint,p_event_type text) returns void language plpgsql security definer set search_path='' as $$ begin if p_event_type not in ('view','whatsapp') then raise exception 'invalid event type'; end if; if not exists(select 1 from public.vehicles where id=p_vehicle_id and status='disponivel') then return; end if; insert into public.vehicle_events(vehicle_id,event_type) values(p_vehicle_id,p_event_type); end $$;
revoke all on function public.track_vehicle_event(bigint,text) from public;
grant execute on function public.track_vehicle_event(bigint,text) to anon,authenticated;

