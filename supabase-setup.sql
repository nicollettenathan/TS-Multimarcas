create extension if not exists pgcrypto;
create schema if not exists private;

create table if not exists public.panel_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role text not null default 'editor' check (role in ('super_admin','owner','admin','editor')),
  display_name text,
  created_at timestamptz not null default now()
);
alter table public.panel_users enable row level security;

create or replace function private.current_panel_role()
returns text language sql stable security definer set search_path=''
as $$ select role from public.panel_users where user_id=(select auth.uid()) limit 1 $$;
create or replace function private.can_manage_stock()
returns boolean language sql stable security definer set search_path=''
as $$ select coalesce(private.current_panel_role() in ('super_admin','owner','admin','editor'),false) $$;
create or replace function private.can_delete_stock()
returns boolean language sql stable security definer set search_path=''
as $$ select coalesce(private.current_panel_role() in ('super_admin','owner','admin'),false) $$;
create or replace function public.current_user_panel_role()
returns text language sql stable set search_path=''
as $$ select private.current_panel_role() $$;

revoke all on schema private from public;
grant usage on schema private to anon,authenticated;
revoke all on function private.current_panel_role() from public,anon;
grant execute on function private.current_panel_role() to authenticated;
revoke all on function private.can_manage_stock() from public;
grant execute on function private.can_manage_stock() to anon,authenticated;
revoke all on function private.can_delete_stock() from public,anon;
grant execute on function private.can_delete_stock() to authenticated;
revoke all on function public.current_user_panel_role() from public,anon;
grant execute on function public.current_user_panel_role() to authenticated;

revoke all on public.panel_users from anon,authenticated;
grant select on public.panel_users to authenticated;
drop policy if exists "Panel user can read own role" on public.panel_users;
create policy "Panel user can read own role" on public.panel_users for select to authenticated
using (user_id=(select auth.uid()) or private.current_panel_role() in ('super_admin','owner'));

create table if not exists public.vehicles (
  id bigint generated by default as identity primary key,
  title text not null default '',
  brand text not null default '',
  model text not null default '',
  year text not null default '',
  km text not null default '',
  transmission text not null default '',
  price text not null default '',
  image text not null default '',
  status text not null default 'disponivel' check (status in ('disponivel','vendido','arquivado')),
  featured boolean not null default false,
  created_at timestamptz not null default now(),
  name text not null default '',
  version text not null default '',
  model_year text not null default '',
  fuel text not null default '',
  color text not null default '',
  description text not null default '',
  images text[] not null default '{}',
  promo_price text not null default '',
  slug text,
  constraint vehicles_max_10_images check (cardinality(images)<=10)
);
create unique index if not exists vehicles_slug_uidx on public.vehicles(slug) where slug is not null;
alter table public.vehicles enable row level security;

drop policy if exists "Public can view available vehicles" on public.vehicles;
create policy "Public can view available vehicles" on public.vehicles for select to anon,authenticated
using (status='disponivel' or private.can_manage_stock());
drop policy if exists "Team can insert vehicles" on public.vehicles;
create policy "Team can insert vehicles" on public.vehicles for insert to authenticated with check (private.can_manage_stock());
drop policy if exists "Team can update vehicles" on public.vehicles;
create policy "Team can update vehicles" on public.vehicles for update to authenticated using (private.can_manage_stock()) with check (private.can_manage_stock());
drop policy if exists "Managers can delete vehicles" on public.vehicles;
create policy "Managers can delete vehicles" on public.vehicles for delete to authenticated using (private.can_delete_stock());
grant select on public.vehicles to anon;
grant select,insert,update,delete on public.vehicles to authenticated;
grant usage,select on sequence public.vehicles_id_seq to authenticated;

create or replace function public.vehicle_slug_base(input text)
returns text language sql immutable set search_path=''
as $$ select trim(both '-' from regexp_replace(regexp_replace(lower(translate(coalesce(input,''),'áàãâäéèêëíìîïóòõôöúùûüçñÁÀÃÂÄÉÈÊËÍÌÎÏÓÒÕÔÖÚÙÛÜÇÑ','aaaaaeeeeiiiiooooouuuucnAAAAAEEEEIIIIOOOOOUUUUCN')),'[^a-z0-9]+','-','g'),'-+','-','g')) $$;
create or replace function private.set_vehicle_slug()
returns trigger language plpgsql security definer set search_path=''
as $$ begin if new.slug is null or btrim(new.slug)='' then new.slug:=coalesce(nullif(public.vehicle_slug_base(new.name),''),'veiculo')||'-'||new.id::text; end if; return new; end $$;
drop trigger if exists set_vehicle_slug on public.vehicles;
create trigger set_vehicle_slug before insert on public.vehicles for each row execute function private.set_vehicle_slug();

