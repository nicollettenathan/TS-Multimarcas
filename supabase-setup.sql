create or replace function private.current_panel_display_name()
returns text language sql stable security definer set search_path=''
as $$ select coalesce((select display_name from public.panel_users where user_id=auth.uid()),(select email from auth.users where id=auth.uid()),'Sistema') $$;
revoke all on function private.current_panel_display_name() from public,anon,authenticated;

create or replace function private.log_vehicle_activity()
returns trigger language plpgsql security definer set search_path=''
as $$ declare uid uuid:=auth.uid(); role_name text:=private.current_panel_role(); actor_label text:=private.current_panel_display_name(); clean_old jsonb; clean_new jsonb; begin
if tg_op='INSERT' then insert into public.activity_logs(actor_user_id,actor_role,actor_name,action,entity_type,entity_id,entity_label,details) values(uid,role_name,actor_label,'vehicle_created','vehicle',new.id::text,new.name,jsonb_build_object('after',to_jsonb(new)-'images'-'image'-'description')); return new;
elsif tg_op='UPDATE' then clean_old:=to_jsonb(old)-'images'-'image'-'description'; clean_new:=to_jsonb(new)-'images'-'image'-'description'; if clean_old is distinct from clean_new or old.images is distinct from new.images then insert into public.activity_logs(actor_user_id,actor_role,actor_name,action,entity_type,entity_id,entity_label,details) values(uid,role_name,actor_label,'vehicle_updated','vehicle',new.id::text,new.name,jsonb_build_object('before',clean_old,'after',clean_new,'photos_before',cardinality(old.images),'photos_after',cardinality(new.images))); end if; return new;
elsif tg_op='DELETE' then insert into public.activity_logs(actor_user_id,actor_role,actor_name,action,entity_type,entity_id,entity_label,details) values(uid,role_name,actor_label,'vehicle_deleted','vehicle',old.id::text,old.name,jsonb_build_object('before',to_jsonb(old)-'images'-'image'-'description')); return old; end if; return null; end $$;
drop trigger if exists log_vehicle_activity on public.vehicles;
create trigger log_vehicle_activity after insert or update or delete on public.vehicles for each row execute function private.log_vehicle_activity();

create table if not exists public.leads (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  whatsapp text not null,
  brand text not null,
  model text not null,
  year text not null default '',
  km text not null default '',
  notes text not null default '',
  status text not null default 'novo' check (status in ('novo','em_contato','avaliacao','comprado','descartado')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.leads enable row level security;
grant insert on public.leads to anon,authenticated;
grant select,update on public.leads to authenticated;
drop policy if exists "Public can submit leads" on public.leads;
create policy "Public can submit leads" on public.leads for insert to anon,authenticated with check (length(btrim(name)) between 2 and 100 and length(regexp_replace(whatsapp,'[^0-9]','','g')) between 10 and 13 and length(btrim(brand)) between 1 and 80 and length(btrim(model)) between 1 and 120);
drop policy if exists "Managers can view leads" on public.leads;
create policy "Managers can view leads" on public.leads for select to authenticated using (private.current_panel_role() in ('super_admin','owner','admin'));
drop policy if exists "Managers can update leads" on public.leads;
create policy "Managers can update leads" on public.leads for update to authenticated using (private.current_panel_role() in ('super_admin','owner','admin')) with check (private.current_panel_role() in ('super_admin','owner','admin'));
create or replace function private.touch_lead_updated_at() returns trigger language plpgsql set search_path='' as $$ begin new.updated_at:=now(); return new; end $$;
drop trigger if exists touch_lead_updated_at on public.leads;
create trigger touch_lead_updated_at before update on public.leads for each row execute function private.touch_lead_updated_at();
create or replace function private.log_lead_activity() returns trigger language plpgsql security definer set search_path='' as $$ begin if tg_op='INSERT' then insert into public.activity_logs(actor_user_id,actor_role,actor_name,action,entity_type,entity_id,entity_label,details) values(auth.uid(),private.current_panel_role(),case when auth.uid() is null then 'Visitante' else private.current_panel_display_name() end,'lead_created','lead',new.id::text,new.name,jsonb_build_object('brand',new.brand,'model',new.model,'status',new.status)); elsif tg_op='UPDATE' and old.status is distinct from new.status then insert into public.activity_logs(actor_user_id,actor_role,actor_name,action,entity_type,entity_id,entity_label,details) values(auth.uid(),private.current_panel_role(),private.current_panel_display_name(),'lead_status_changed','lead',new.id::text,new.name,jsonb_build_object('from',old.status,'to',new.status)); end if; return new; end $$;
drop trigger if exists log_lead_activity on public.leads;
create trigger log_lead_activity after insert or update on public.leads for each row execute function private.log_lead_activity();

